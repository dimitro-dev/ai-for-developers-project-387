/**
 * Owner-хелперы вне `components.registry.xml`: реестр перечисляет только функции, вызываемые
 * из bind-выражений `{fn(...)}` спеков (см. комментарий в самом реестре); `generatePublicId`
 * вызывается действием состояния экрана (`afterWhen` спеки 10), а не биндом разметки, поэтому
 * записи в реестре не требует.
 */

/**
 * Посимвольная транслитерация кириллицы в латиницу для генерации slug'а. Твёрдый и мягкий знак
 * вырезаются, остальные буквы — по общей схеме (без привязки к конкретному ГОСТу/ISO 9).
 */
const CYRILLIC_TO_LATIN: Readonly<Record<string, string>> = {
  а: 'a',
  б: 'b',
  в: 'v',
  г: 'g',
  д: 'd',
  е: 'e',
  ё: 'e',
  ж: 'zh',
  з: 'z',
  и: 'i',
  й: 'i',
  к: 'k',
  л: 'l',
  м: 'm',
  н: 'n',
  о: 'o',
  п: 'p',
  р: 'r',
  с: 's',
  т: 't',
  у: 'u',
  ф: 'f',
  х: 'h',
  ц: 'c',
  ч: 'ch',
  ш: 'sh',
  щ: 'sch',
  ъ: '',
  ы: 'y',
  ь: '',
  э: 'e',
  ю: 'yu',
  я: 'ya',
};

/**
 * Публичный id типа события из названия — screen 10, действие `changeTitle`
 * (`afterWhen="!$state.publicIdTouched:generatePublicId"`): пока владелец не тронул поле id
 * вручную, оно перегенерируется при каждом изменении названия. Формат — правило спеки
 * `public-id-format`: латиница в нижнем регистре, цифры и одиночные дефисы, без ведущего и
 * хвостового дефиса; финально уникальность и формат проверяет сервер.
 *
 * Транслитерация кириллицы не описана ни в спеке, ни в registry — продукт русскоязычный, и
 * названия типов событий («Консультация», «Демо-встреча») почти всегда кириллические: без
 * транслитерации автогенерация обычно давала бы пустой id, что расходится с целью UX-правила
 * («генерируется из названия»). Решение зафиксировано здесь как явный выбор реализации.
 */
export function generatePublicId(name: string): string {
  const transliterated = Array.from(name.toLowerCase())
    .map((character) => CYRILLIC_TO_LATIN[character] ?? character)
    .join('');

  return transliterated.replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}
